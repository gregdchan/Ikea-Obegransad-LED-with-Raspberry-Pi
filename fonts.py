if __name__ == "__main__":
    # Self-check + ASCII preview:  python3 fonts.py            -> dump every glyph
    #                              python3 fonts.py "Hello!"   -> preview a string in both fonts
    import sys

    assert all(0 <= b <= 0x7F for b in System6x7), "large glyph byte out of 7-row range"
    assert all(0 <= b <= 0x1F for b in SmallFont4x5), "small glyph byte out of 5-row range (top would be cut off)"
    assert all(p + 6 <= len(System6x7) for p in char_map.values())
    assert all(p + 4 <= len(SmallFont4x5) for p in small_char_map.values())

    def _grid(cols, rows):
        return [''.join('#' if c & (1 << r) else '.' for c in cols) for r in range(rows)]

    def _show(chars, get_cols, rows, per_line):
        for i in range(0, len(chars), per_line):
            group = chars[i:i + per_line]
            grids = [_grid(get_cols(ch), rows) for ch in group]
            width = len(grids[0][0])
            print('   '.join(repr(ch).ljust(width) for ch in group))
            for r in range(rows):
                print('   '.join(g[r] for g in grids))
            print()

    text = sys.argv[1] if len(sys.argv) > 1 else None
    large = lambda ch: System6x7[char_map[ch]:char_map[ch] + 6]
    small = lambda ch: SmallFont4x5[small_char_map[ch]:small_char_map[ch] + 4]

    if text:
        print("LARGE (6x7):")
        _show([c for c in text.upper() if c in char_map], large, 7, 8)
        print("SMALL (4x5, as used for scrolling):")
        _show([c for c in text.lower() if c in small_char_map], small, 5, 12)
    else:
        print("LARGE FONT (6x7)\n")
        _show(list(char_map), large, 7, 8)
        print("SMALL FONT (4x5)\n")
        _show(list(small_char_map), small, 5, 12)
    print("self-check ok")
